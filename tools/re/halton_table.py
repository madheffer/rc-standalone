"""halton_table.py <s0_f0.hlsl> <out.cs> -- the scrambled Halton digit table from rtx_generate_scrambled_halton_samples.

scenesystem's compute shader (core shaders_vulkan, rtx_generate_scrambled_halton_samples_vulkan_60_cs)
evaluates dimension d of sample index i as

    float(sum_k perm[offset_d + (i / div_k) % mod_d] * mult_k) * scale_d

with perm the uint16 table in textures/dev/scrambled_halton.vdata, and dimension 0 as the
plain base-2 radical inverse. The groups per prime vary (3 in fives, 17 in pairs, 23 alone),
so this reads every case of both switches straight from the decompile and writes them as a
C# table (Lighting/Bake/HaltonTable.cs).
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()

# The two switches: the first sets _19095 (dimension 2z), the second _33359 (2z + 1).
cases = {}
for m in re.finditer(r"case (\d+)u:\s*\{(.*?)\n            \}", src, re.S):
    d = int(m.group(1))
    body = m.group(2)
    if d in cases:
        continue
    if d == 0:
        cases[0] = None
        continue
    groups = []
    for g in re.finditer(r"uint _\d+ = (?:(\d+)u \+ )?\(?(?:\(_12091 / (\d+)u\)|_12091) % (\d+)u\)?;", body):
        offset = int(g.group(1) or 0)
        div = int(g.group(2) or 1)
        mod = int(g.group(3))
        groups.append((offset, div, mod))
    # Some cases fold the offset into the halving: (368u + _x) / 2u.
    folded = re.findall(r"\((\d+)u \+ _\d+\) / 2u", body)
    if folded:
        off = int(folded[0])
        groups = [(off, div, mod) for (_, div, mod) in groups]
    sm = re.search(r"= float\((.*)\) \* ([0-9.e+-]+)f;", body)
    mults = [int(x) for x in re.findall(r"\* (\d+)u\)", sm.group(1))] + [1]
    scale = sm.group(2)
    if len(mults) != len(groups):
        sys.exit(f"case {d}: {len(groups)} groups, {len(mults)} multipliers")
    cases[d] = (groups, mults, scale)

dims = sorted(cases)
assert dims == list(range(len(dims))), dims
with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/re/halton_table.py from rtx_generate_scrambled_halton_samples_vulkan_60_cs: do not edit.\n")
    f.write("namespace Source2.Compiler.Lighting.Bake;\n\n")
    f.write("internal static partial class HaltonSamples\n{\n")
    f.write("    // Per dimension (1..): (permutation offset, divisor, modulus) per digit group, multipliers, scale.\n")
    f.write("    private static readonly (int Offset, uint Div, uint Mod)[][] Groups =\n    [\n        [],\n")
    for d in dims[1:]:
        g = ", ".join(f"({o}, {dv}u, {md}u)" for o, dv, md in cases[d][0])
        f.write(f"        [{g}],\n")
    f.write("    ];\n\n    private static readonly uint[][] Multipliers =\n    [\n        [],\n")
    for d in dims[1:]:
        f.write("        [" + ", ".join(f"{x}u" for x in cases[d][1]) + "],\n")
    f.write("    ];\n\n    private static readonly float[] Scales =\n    [\n        0f,\n")
    for d in dims[1:]:
        f.write(f"        {cases[d][2]}f,\n")
    f.write("    ];\n}\n")
print(len(dims), "dimensions")
