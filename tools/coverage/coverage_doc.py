"""coverage_doc.py <fgd_classes.json> <class_refs.json> <map_classes.json> <fgd_keys.json> <out.md>: the entity
half of docs/COVERAGE.md. Every placeable class the game's FGDs declare (offered: the ones csgo.fgd's @include
chain loads and does not @exclude, as fgd_keys.json from CoverageKeysProbe holds them), with the compile DLLs that name it,
what the compile does with it (tools/coverage/class_notes.json, read from the decompiles), the local
maps that hold it and whether one of those maps has its lumps pinned against Valve's compile.
The compile option half is hand-kept in docs/COVERAGE.md below the generated part."""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PLACEABLE = ("PointClass", "SolidClass", "NPCClass", "KeyFrameClass", "MoveClass", "FilterClass",
             "PathNodeClass", "PathClass", "CableClass")
# Maps whose every lump EntityLumpAgainstValveTests compares against Valve's compile.
PINNED = ["probe_classes", "cardtest", "probe01", "ze_hold_em_p", "atixref", "ze_doom_p2_c_gameplay",
          "c2m2_fairgrounds_csgo_gameplay", "ze_ffvii_mako_reactor_v6_p"]
# Classes that still differ in those tests (their "differs:" lines), with the reason.
LIGHT = "light export (shape keys, matrix angles) and baked keys not ported"
PROBE = "baked keys (atlas textures, handshake, size) not ported"
ANGLES = "Mako world-layer instance copies: angles 1 or 2 ulps off (parked)"
GAPS = {"light_omni2": LIGHT, "light_barn": LIGHT, "light_environment": LIGHT, "light_rect": LIGHT,
        "env_combined_light_probe_volume": PROBE, "env_light_probe_volume": PROBE,
        "env_cubemap_box": "baked keys (cubemaptexture, handshake) not ported",
        "cable_dynamic": "rendercolor ships untyped; the write is not read yet",
        "func_movelinear": ANGLES, "info_particle_system": ANGLES, "point_soundevent": ANGLES}

def gap(name):
    return GAPS.get(name)

fgd = json.load(open(sys.argv[1]))
refs = json.load(open(sys.argv[2]))
present = json.load(open(sys.argv[3]))
offered = json.load(open(sys.argv[4]))
GAME = r"D:\Steam\steamapps\common\Counter-Strike Global Offensive\game"
excluded = set()
for root in ("core", "csgo_core", "csgo"):
    for dirpath, dirs, names in os.walk(os.path.join(GAME, root)):
        dirs[:] = [x for x in dirs if x != "import_scripts"]
        for n in names:
            if n.endswith(".fgd"):
                excluded.update(re.findall(r"@exclude\s+(\w+)", open(os.path.join(dirpath, n), encoding="utf-8", errors="replace").read()))
notes_path = os.path.join(HERE, "class_notes.json")
notes = json.load(open(notes_path)) if os.path.exists(notes_path) else {}

rows = []
hidden = []
for name, c in fgd.items():
    if c["kind"] not in PLACEABLE:
        continue
    if name not in offered:
        hidden.append((name, c["fgd"].split("/")[-1], "excluded by @exclude" if name in excluded
                       else "its FGD is not in csgo.fgd's @include chain", present.get(name, [])))
        continue
    dlls = [d.replace("tools/", "").replace(".dll", "") for d in refs.get(name, []) if d != "tools/hammer.dll"]
    maps = present.get(name, [])
    pinned = [m for m in maps if m in PINNED]
    g = gap(name)
    if pinned and not g:
        status = "exact"
    elif pinned:
        status = "partial"
    elif maps:
        status = "unpinned"
    else:
        status = "no sample"
    rows.append((name, c["kind"].replace("Class", ""), c["fgd"].split("/")[-1], dlls, maps, pinned, status, g,
                 notes.get(name, {})))

special = [r for r in rows if r[3]]
plain = [r for r in rows if not r[3]]
count = lambda rs, s: sum(1 for r in rs if r[6] == s)

out = []
w = out.append
w("<!-- generated by tools/coverage/coverage_doc.py; edit the script or class_notes.json, not this part -->")
w("## Entity classes")
w("")
w(f"{len(rows)} placeable classes are offered: the ones csgo.fgd loads through its @include chain and does not")
w(f"@exclude. {len(hidden)} more are declared in FGD files but not offered (listed last); a map can still carry")
w("one (Mako holds info_world_layer entities), and the compile then treats it as a class the FGD does not know.")
w(f"{len(special)} of them are named by a compile DLL, so the compile does something with them beyond copying")
w(f"their keys into the entity lump. The other {len(plain)} only pass through the lump writer, which is driven by")
w("the FGD's key types for every class alike.")
w("")
w("Status:")
w("- **exact**: present in a map whose every lump is compared against Valve's compile, with no allowed difference.")
w("- **partial**: present in such a map, and some of its keys still differ (reason given).")
w("- **unpinned**: present in a local map, but none with a pinned compile.")
w("- **no sample**: no local map holds it; a probe map is needed.")
w("")
for title, rs in (("Classes the compile handles", special), ("Classes that only pass through the lump", plain)):
    w(f"### {title}")
    w("")
    w(f"exact {count(rs, 'exact')}, partial {count(rs, 'partial')}, unpinned {count(rs, 'unpinned')}, "
      f"no sample {count(rs, 'no sample')}")
    w("")
    if rs is special:
        w("| class | kind | named by | what the compile does | port | status |")
        w("|---|---|---|---|---|---|")
        for name, kind, f, dlls, maps, pinned, status, g, n in sorted(rs):
            st = status + (f" ({g})" if g else "")
            w(f"| {name} | {kind} | {', '.join(dlls)} | {n.get('compile', 'not read yet')} | {n.get('port', '')} | {st} |")
    else:
        w("| class | kind | fgd | local maps | status |")
        w("|---|---|---|---|---|")
        for name, kind, f, dlls, maps, pinned, status, g, n in sorted(rs):
            shown = ", ".join(pinned[:2] or maps[:2]) + (f" +{len(maps) - 2}" if len(maps) > 2 else "")
            st = status + (f" ({g})" if g else "")
            w(f"| {name} | {kind} | {f} | {shown} | {st} |")
    w("")
w("### Declared but not offered")
w("")
w("| class | fgd | why | what the compile does | port | local maps |")
w("|---|---|---|---|---|---|")
for name, f, why, maps in sorted(hidden):
    n = notes.get(name, {})
    shown = ", ".join(maps[:3]) + (f" +{len(maps) - 3}" if len(maps) > 3 else "")
    w(f"| {name} | {f} | {why} | {n.get('compile', '')} | {n.get('port', '')} | {shown} |")
w("")
w("<!-- end generated -->")

md = sys.argv[5]
text = open(md, encoding="utf-8").read() if os.path.exists(md) else ""
start, end = "<!-- generated by", "<!-- end generated -->"
if start in text:
    head = text[:text.index(start)]
    tail = text[text.index(end) + len(end):]
else:
    head, tail = text, ""
open(md, "w", encoding="utf-8", newline="\n").write(head + "\n".join(out) + tail)
print(len(rows), "classes;", len(special), "handled;", {s: count(rows, s) for s in ("exact", "partial", "unpinned", "no sample")})
